"""The disposable ``PI_CODING_AGENT_DIR`` and the disposable extension directory.

Exclusion by redirection (AR0 section 3.13): pointing ``PI_CODING_AGENT_DIR`` at
an AIDO-authored directory means the real ``~/.pi/agent/auth.json``,
``settings.json``, ``models.json``, ``trust.json`` and ``sessions/`` are not the
ones Pi reads at all. AR1 never reads, copies, or inspects the user's real Pi
configuration.

Two hard rules live here:

1. **The generated ``models.json`` MUST OMIT ``maxTokens``** (AR0-FU1 section 11).
   A value AIDO writes into a file AIDO generates is AIDO-configured, whatever
   field it lands in, so writing one would make
   ``aido_requested_max_output_tokens: null`` a false label.
2. **``apiKey`` uses the ``$ENV`` interpolation form only.** Pi's ``!shell``
   credential resolution is never used, in any file, ever.
"""

from __future__ import annotations

import json
import os
import shutil
from dataclasses import dataclass
from pathlib import Path

from .environment import ROUTE_PLACEHOLDER_ENV_NAME

EXTENSION_SOURCE_FILES: tuple[str, ...] = (
    "confinement.ts",
    "tools.ts",
    "index.ts",
    "package.json",
)

SENTINEL_COMMAND_NAME = "aido_confinement_active"
TOOL_ALLOWLIST: tuple[str, ...] = ("aido_read", "aido_edit")

# AR1-FU1: the one known-expected value of Pi 0.84.2's ``sourceInfo.source`` for
# a command that came from an explicitly CLI-loaded ``-e``/``--extension``
# extension (confirmed by a live no-prompt handshake; see FINDINGS.md section
# 3). H1 requires this value when Pi reports a source-origin field at all, and
# refuses on any other reported value rather than ignoring the contradiction.
EXPECTED_EXTENSION_SOURCE_KIND = "cli"

_GENERATED_CONFIG_HEADER = """\
/* GENERATED by the AIDO AR1 harness. Do not edit by hand.
 *
 * Holds the exact absolute allowlist AIDO computed with its own accepted
 * canonical-path machinery, before Pi was launched. The extension performs no
 * path policy of its own -- it consumes this concrete list.
 */
import type { AidoAr1Config } from "./confinement.ts";

export const AIDO_AR1_CONFIG: AidoAr1Config = %s;
"""


class PiConfigError(Exception):
    """The disposable Pi configuration could not be generated."""


@dataclass(frozen=True)
class DisposablePiConfig:
    """Absolute paths of the generated, disposable Pi configuration."""

    config_dir: str
    settings_path: str
    models_path: str
    extension_dir: str
    extension_entry: str
    provider_id: str
    model_id: str
    models_json_omits_max_tokens: bool
    api_key_resolution: str  # always "env_interpolation"


def write_disposable_pi_config(
    experiment_root: str,
    *,
    provider_id: str,
    model_id: str,
    base_url: str,
) -> tuple[str, str, str]:
    """Write ``settings.json`` and ``models.json`` into a fresh config dir.

    ``base_url`` is written into the disposable file and is NEVER recorded,
    printed, or echoed anywhere else.
    """
    config_dir = Path(experiment_root) / "pi_config"
    config_dir.mkdir(parents=True, exist_ok=False)

    settings = {
        # No ambient resources of any kind.
        "packages": [],
        "extensions": [],
        "skills": [],
        "prompts": [],
        "themes": [],
        "defaultTools": [],
        "enableSkillCommands": False,
        # Never silently trust project-local .pi resources in a non-interactive mode.
        "defaultProjectTrust": "never",
        # No startup network chatter beyond what --offline already blocks.
        "enableInstallTelemetry": False,
        "enableAnalytics": False,
        "quietStartup": True,
        # Pi owns its own provider-transport retry; AIDO does not. Recording it
        # explicitly keeps "runtime retry" and "AIDO semantic attempt" disjoint.
        "retry": {
            "enabled": True,
            "maxRetries": 3,
            "baseDelayMs": 2000,
            "provider": {"maxRetries": 0},
        },
    }
    settings_path = config_dir / "settings.json"
    settings_path.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")

    models = {
        "providers": {
            provider_id: {
                "baseUrl": base_url,
                "api": "openai-completions",
                # $ENV interpolation. The variable carries a fixed NON-SECRET
                # placeholder, because the endpoint is keyless. A placeholder is
                # not authentication and must never be described as one.
                "apiKey": f"${ROUTE_PLACEHOLDER_ENV_NAME}",
                "compat": {
                    "supportsDeveloperRole": False,
                    "supportsReasoningEffort": False,
                },
                "models": [
                    {
                        "id": model_id,
                        "reasoning": True,
                        # NOTE: maxTokens is deliberately ABSENT. See module docstring.
                    }
                ],
            }
        }
    }
    models_path = config_dir / "models.json"
    models_text = json.dumps(models, indent=2) + "\n"
    if "maxTokens" in models_text:
        raise PiConfigError(
            "config error: the generated models.json must not contain maxTokens"
        )
    if "!" in models_text.split('"apiKey"')[1].split("\n")[0]:
        raise PiConfigError(
            "config error: models.json apiKey must never use '!shell' resolution"
        )
    models_path.write_text(models_text, encoding="utf-8")

    return str(config_dir), str(settings_path), str(models_path)


def write_disposable_extension(
    experiment_root: str,
    *,
    source_dir: str,
    repo_root: str,
    read_allowlist: tuple[str, ...],
    edit_allowlist: tuple[str, ...],
    experiment_id: str,
) -> tuple[str, str]:
    """Copy the static extension sources and generate ``ar1_config.ts``.

    The extension sources are static and reviewable in the repository; only the
    concrete allowlist is generated, which is exactly FU1's B-fixed shape.
    """
    extension_dir = Path(experiment_root) / "pi_extension"
    extension_dir.mkdir(parents=True, exist_ok=False)

    for name in EXTENSION_SOURCE_FILES:
        source = Path(source_dir) / name
        if not source.is_file():
            raise PiConfigError(f"config error: extension source {name!r} is missing")
        shutil.copyfile(source, extension_dir / name)

    for entry in (*read_allowlist, *edit_allowlist, repo_root):
        if not os.path.isabs(entry):
            raise PiConfigError(
                "config error: every allowlist entry must be an absolute path"
            )

    config = {
        "experiment": experiment_id,
        "cwd": repo_root,
        "readAllowlist": list(read_allowlist),
        "editAllowlist": list(edit_allowlist),
    }
    generated = _GENERATED_CONFIG_HEADER % json.dumps(config, indent=2, ensure_ascii=True)
    (extension_dir / "ar1_config.ts").write_text(generated, encoding="utf-8")

    entry = str(extension_dir / "index.ts")
    return str(extension_dir), entry


def describe_generated_config(
    *, settings_path: str, models_path: str
) -> dict[str, object]:
    """A recordable, secret-free description of what was generated.

    Reads the generated files back and reports only structural facts: which keys
    exist, whether ``maxTokens`` is absent, and how ``apiKey`` resolves. It never
    reports the base URL, the apiKey expression's resolved value, or any host.
    """
    settings = json.loads(Path(settings_path).read_text(encoding="utf-8"))
    models = json.loads(Path(models_path).read_text(encoding="utf-8"))
    provider_ids = sorted(models.get("providers", {}))
    provider = models["providers"][provider_ids[0]] if provider_ids else {}
    model_entries = provider.get("models", [])
    api_key_expression = provider.get("apiKey", "")
    return {
        "settings_keys": sorted(settings),
        "settings_ambient_sources_emptied": all(
            settings.get(key) == [] for key in ("packages", "extensions", "skills", "prompts", "themes")
        ),
        "settings_default_project_trust": settings.get("defaultProjectTrust"),
        "models_provider_ids": provider_ids,
        "models_provider_api": provider.get("api"),
        "models_model_ids": [entry.get("id") for entry in model_entries],
        "models_json_contains_max_tokens": any(
            "maxTokens" in entry for entry in model_entries
        )
        or "maxTokens" in provider,
        "api_key_resolution": (
            "env_interpolation"
            if api_key_expression.startswith("$") and not api_key_expression.startswith("$$")
            else "other"
        ),
        "api_key_uses_shell_command_resolution": api_key_expression.startswith("!"),
        "api_key_env_variable_name": api_key_expression.lstrip("$")
        if api_key_expression.startswith("$")
        else None,
        "base_url_recorded": False,
    }
