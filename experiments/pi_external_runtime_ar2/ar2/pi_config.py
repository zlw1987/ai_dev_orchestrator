"""The disposable ``PI_CODING_AGENT_DIR`` and the disposable extension directory.

Exclusion by redirection: pointing ``PI_CODING_AGENT_DIR`` at an AIDO-authored
directory means the real ``~/.pi/agent/auth.json``, ``settings.json``,
``models.json``, ``trust.json`` and ``sessions/`` are not the ones Pi reads at
all. AR2 never reads, copies, or inspects the user's real Pi configuration.

Three hard rules live here:

1. **The generated ``models.json`` MUST OMIT ``maxTokens``.** AIDO imposes no
   model output-token ceiling by default, and a value AIDO writes into a file
   AIDO generates is AIDO-configured whatever field it lands in -- so writing one
   would make ``aido_requested_max_output_tokens: null`` a false label. Pi-native
   and catalog limits are a different field and a different fact.
2. **``apiKey`` uses the ``$ENV`` interpolation form only.** Pi's ``!shell``
   credential resolution is never used, in any file, ever.
3. **The generated ``ar2_config.ts`` carries the per-run pipe name, capability id
   and token, and nothing else.** No new environment variable is introduced, so
   AR1's recorded environment evidence transfers unchanged. The token is never
   printed, never logged, never recorded, and never enters a model prompt.
"""

from __future__ import annotations

import json
import os
import shutil
from dataclasses import dataclass
from pathlib import Path

from .environment import ROUTE_PLACEHOLDER_ENV_NAME

EXTENSION_SOURCE_FILES: tuple[str, ...] = (
    "ipc.ts",
    "tools.ts",
    "index.ts",
    "package.json",
)

SENTINEL_COMMAND_NAME = "aido_ar2_broker_active"
TOOL_ALLOWLIST: tuple[str, ...] = ("aido_read", "aido_edit")

# Pi 0.84.2's known-expected ``sourceInfo.source`` for a command that came from
# an explicitly CLI-loaded ``--extension`` extension (confirmed live in AR1-FU1).
EXPECTED_EXTENSION_SOURCE_KIND = "cli"

_GENERATED_CONFIG_HEADER = """\
/* GENERATED by the AIDO AR2 harness. Do not edit by hand. Disposable.
 *
 * Carries the per-run broker endpoint and the per-run capability binding, which
 * AIDO generated and owns. These values:
 *   - never enter a model prompt;
 *   - are never logged, printed, or written to an experiment artifact;
 *   - are discarded with this directory at teardown.
 *
 * They are an INTEGRITY AND ATTRIBUTION control, not OS isolation against a
 * same-user adversary -- that adversary can read this file, and does not need
 * the broker at all.
 */
export interface AidoAr2Config {
  readonly experiment: string;
  readonly pipeName: string;
  readonly capabilityId: string;
  readonly token: string;
}

export const AIDO_AR2_CONFIG: AidoAr2Config = %s;
"""


class PiConfigError(Exception):
    """The disposable Pi configuration could not be generated."""


@dataclass(frozen=True)
class GeneratedExtension:
    """Where the disposable extension landed. The token is NOT carried here."""

    extension_dir: str
    extension_entry: str
    source_file_names: tuple[str, ...]


def write_disposable_pi_config(
    experiment_root: str, *, provider_id: str, model_id: str, base_url: str
) -> tuple[str, str, str]:
    """Write ``settings.json`` and ``models.json`` into a fresh config dir.

    ``base_url`` is written into the disposable file and is NEVER recorded,
    printed, or echoed anywhere else.
    """
    config_dir = Path(experiment_root) / "pi_config"
    config_dir.mkdir(parents=True, exist_ok=False)

    settings = {
        "packages": [],
        "extensions": [],
        "skills": [],
        "prompts": [],
        "themes": [],
        "defaultTools": [],
        "enableSkillCommands": False,
        "defaultProjectTrust": "never",
        "enableInstallTelemetry": False,
        "enableAnalytics": False,
        "quietStartup": True,
        # Pi owns its own provider-transport retry; AIDO does not. Recording it
        # explicitly keeps "runtime retry" and "AIDO semantic prompt" disjoint.
        "retry": {
            "enabled": True,
            "maxRetries": 3,
            "baseDelayMs": 2000,
            "provider": {"maxRetries": 0},
        },
    }
    settings_path = config_dir / "settings.json"
    settings_path.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")

    models = {
        "providers": {
            provider_id: {
                "baseUrl": base_url,
                "api": "openai-completions",
                # $ENV interpolation. The variable carries a fixed NON-SECRET
                # placeholder because the endpoint is keyless. A placeholder is
                # not authentication and must never be described as one.
                "apiKey": f"${ROUTE_PLACEHOLDER_ENV_NAME}",
                "compat": {
                    "supportsDeveloperRole": False,
                    "supportsReasoningEffort": False,
                },
                "models": [
                    {
                        "id": model_id,
                        "reasoning": True,
                        # NOTE: maxTokens is deliberately ABSENT. See rule 1.
                    }
                ],
            }
        }
    }
    models_path = config_dir / "models.json"
    models_text = json.dumps(models, indent=2) + "\n"
    if "maxTokens" in models_text:
        raise PiConfigError(
            "config error: the generated models.json must not contain maxTokens"
        )
    if "!" in models_text.split('"apiKey"')[1].split("\n")[0]:
        raise PiConfigError(
            "config error: models.json apiKey must never use '!shell' resolution"
        )
    models_path.write_text(models_text, encoding="utf-8")
    return str(config_dir), str(settings_path), str(models_path)


def write_disposable_extension(
    experiment_root: str,
    *,
    source_dir: str,
    experiment_id: str,
    pipe_name: str,
    capability_id: str,
    token: str,
) -> GeneratedExtension:
    """Copy the static extension sources and generate ``ar2_config.ts``.

    The extension sources are static and reviewable in the repository; only the
    per-run endpoint and binding are generated. The generated file is the ONLY
    place the token exists on disk, and it lives inside the disposable root.
    """
    extension_dir = Path(experiment_root) / "pi_extension"
    extension_dir.mkdir(parents=True, exist_ok=False)

    for name in EXTENSION_SOURCE_FILES:
        source = Path(source_dir) / name
        if not source.is_file():
            raise PiConfigError(f"config error: extension source {name!r} is missing")
        shutil.copyfile(source, extension_dir / name)

    config = {
        "experiment": experiment_id,
        "pipeName": pipe_name,
        "capabilityId": capability_id,
        "token": token,
    }
    generated = _GENERATED_CONFIG_HEADER % json.dumps(config, indent=2, ensure_ascii=True)
    (extension_dir / "ar2_config.ts").write_text(generated, encoding="utf-8")

    return GeneratedExtension(
        extension_dir=str(extension_dir),
        extension_entry=str(extension_dir / "index.ts"),
        source_file_names=tuple(sorted(p.name for p in extension_dir.iterdir())),
    )


def scrub_generated_extension_config(extension_dir: str) -> dict[str, object]:
    """Remove the generated binding file, and VERIFY the removal.

    Called before any decision to preserve a disposable root as evidence, so no
    endpoint-bearing or token-bearing generated file survives into preserved
    evidence. Cleanup is verified rather than assumed.
    """
    target = Path(extension_dir) / "ar2_config.ts"
    existed = target.is_file()
    if existed:
        try:
            os.chmod(target, 0o600)
        except OSError:
            pass
        try:
            target.unlink()
        except OSError:
            pass
    return {
        "generated_binding_file_existed": existed,
        "generated_binding_file_removed": not target.exists(),
        "verified_by_stat": True,
    }


def scrub_generated_pi_config(config_dir: str) -> dict[str, object]:
    """Remove the endpoint-bearing generated ``models.json``, and VERIFY it."""
    target = Path(config_dir) / "models.json"
    existed = target.is_file()
    if existed:
        try:
            os.chmod(target, 0o600)
        except OSError:
            pass
        try:
            target.unlink()
        except OSError:
            pass
    return {
        "generated_models_json_existed": existed,
        "generated_models_json_removed": not target.exists(),
        "verified_by_stat": True,
    }


def describe_generated_config(*, settings_path: str, models_path: str) -> dict[str, object]:
    """A recordable, secret-free description of what was generated.

    Reports only structural facts: which keys exist, whether ``maxTokens`` is
    absent, and how ``apiKey`` resolves. It never reports the base URL, the
    apiKey expression's resolved value, or any host.
    """
    settings = json.loads(Path(settings_path).read_text(encoding="utf-8"))
    models = json.loads(Path(models_path).read_text(encoding="utf-8"))
    provider_ids = sorted(models.get("providers", {}))
    provider = models["providers"][provider_ids[0]] if provider_ids else {}
    model_entries = provider.get("models", [])
    api_key_expression = provider.get("apiKey", "")
    return {
        "settings_keys": sorted(settings),
        "settings_ambient_sources_emptied": all(
            settings.get(key) == []
            for key in ("packages", "extensions", "skills", "prompts", "themes")
        ),
        "settings_default_project_trust": settings.get("defaultProjectTrust"),
        "models_provider_ids": provider_ids,
        "models_provider_api": provider.get("api"),
        "models_model_ids": [entry.get("id") for entry in model_entries],
        "models_json_contains_max_tokens": any("maxTokens" in e for e in model_entries)
        or "maxTokens" in provider,
        "api_key_resolution": (
            "env_interpolation"
            if api_key_expression.startswith("$") and not api_key_expression.startswith("$$")
            else "other"
        ),
        "api_key_uses_shell_command_resolution": api_key_expression.startswith("!"),
        "api_key_env_variable_name": (
            api_key_expression.lstrip("$") if api_key_expression.startswith("$") else None
        ),
        "base_url_recorded": False,
    }
